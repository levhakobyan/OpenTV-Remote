package com.luma.remote.protocol

import kotlin.math.roundToInt

/** HID Generic Desktop: keyboard report 1, relative 3-button mouse + wheel report 2. */
internal object BluetoothHidReports {
    val keyboardDescriptor=intArrayOf(0x05,0x01,0x09,0x06,0xa1,0x01,0x85,0x01,0x05,0x07,0x19,0xe0,0x29,0xe7,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x08,0x81,0x02,0x95,0x01,0x75,0x08,0x81,0x01,0x95,0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07,0x19,0x00,0x29,0x65,0x81,0x00,0xc0).map { it.toByte() }.toByteArray()
    private val mouseDescriptor=intArrayOf(
        0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x02,0x09,0x01,0xa1,0x00,
        0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,
        0x95,0x01,0x75,0x05,0x81,0x01,
        0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x03,0x81,0x06,0xc0,0xc0
    ).map { it.toByte() }.toByteArray()
    fun descriptor(mouse:Boolean)=if(mouse)keyboardDescriptor+mouseDescriptor else keyboardDescriptor.copyOf()
    fun mouse(dx:Float=0f,dy:Float=0f,wheel:Float=0f,pressed:Boolean=false):ByteArray {
        require(dx.isFinite() && dy.isFinite() && wheel.isFinite())
        fun axis(value:Float)=value.coerceIn(-127f,127f).roundToInt().toByte()
        return byteArrayOf(if(pressed)1 else 0,axis(dx),axis(dy),axis(wheel))
    }
}
